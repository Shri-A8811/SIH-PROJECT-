    def _decide_next_step(
        self,
        step_prompt: str,
        user_prompt: str,
        category: Optional[str],
        step_idx: int,
        project_id: str,
        steps_history: Optional[List[PlanStep]] = None,
    ) -> Tuple[str, str, Dict[str, Any]]:
        """Invokes reasoning model to pick next tool action, with deterministic rule fallback."""
        prompt_lower = user_prompt.lower()
        steps_history = steps_history or []

        # Step 1 Deterministic Fast-Route: If step 1 and asking for standards/SOPs/reports/PDF, search first
        if step_idx == 1:
            if any(k in prompt_lower for k in ["sop", "standard", "procedure", "report", "chapter", "section", "find", "extract", "pdf", "make me pdf", "project section"]):
                search_q = user_prompt.strip()
                clean_q = re.sub(
                    r"(?i)\b(make|generate|create|export|give)\s+(me\s+)?(a\s+)?(pdf|word|docx)?(\s+file)?(\s+from|\s+of|\s+for)?\b",
                    "",
                    search_q
                ).strip()
                if clean_q and len(clean_q) >= 3:
                    search_q = clean_q
                return (
                    "I need to search the internal knowledge base for relevant standard operating procedures and technical documentation.",
                    "knowledge_search",
                    {"query": search_q, "category": category, "top_k": 5},
                )
            nums = [float(n) for n in re.findall(r"\d+(?:\.\d+)?", user_prompt)]
            if len(nums) >= 3 and any(k in prompt_lower for k in ["calculate", "thinning", "margin", "deviation", "breach"]):
                return (
                    "I will calculate the wall thinning deviation deterministically.",
                    "calculate_wall_thinning",
                    {"measured_thickness_mm": nums[0], "nominal_thickness_mm": nums[1], "retirement_thickness_mm": nums[2]},
                )

        # Step >= 2: If user asked for PDF, compile into PDF document
        has_generated_pdf = any(s.action == "generate_pdf_report" for s in steps_history)
        if step_idx >= 2 and not has_generated_pdf and any(k in prompt_lower for k in ["pdf", "make me pdf", "generate pdf", "export to pdf"]):
            # Gather search chunks and observations from previous steps
            retrieved_chunks = []
            for s in steps_history:
                if s.action == "knowledge_search" and s.observation and isinstance(s.observation, dict):
                    retrieved_chunks.extend(s.observation.get("results", []))

            sections = []
            citations = []
            findings = []
            for r in retrieved_chunks:
                sec_title = r.get("section_title") or f"Page {r.get('page_number', 1)}"
                content = r.get("content", "")
                doc_name = r.get("document_name", "Technical Document")
                page_no = r.get("page_number", 1)
                sections.append({
                    "title": f"{sec_title} ({doc_name}, Page {page_no})",
                    "content": content,
                })
                citations.append({
                    "document_name": doc_name,
                    "section_title": sec_title,
                    "page_number": page_no,
                    "evidence_id": r.get("evidence_id", "E_RET"),
                })
                findings.append({
                    "asset": doc_name[:25],
                    "reading": sec_title[:30],
                    "standard": f"Page {page_no}",
                    "status": "EXTRACTED & VERIFIED",
                })

            clean_title = re.sub(
                r"(?i)\b(make|generate|create|export|give)\s+(me\s+)?(a\s+)?pdf(\s+file)?(\s+from|\s+of|\s+for)?\b",
                "",
                user_prompt.strip()
            ).strip()
            if not clean_title or len(clean_title) < 3:
                clean_title = (retrieved_chunks[0].get("section_title") if retrieved_chunks else "Technical Documentation")
            title = f"{clean_title.title()} Report"

            summary = (
                f"Technical documentation report compiled from verified internal knowledge base based on user query: '{user_prompt.strip()}'.\n\n"
                f"Source Materials: {', '.join(sorted(list({r.get('document_name') for r in retrieved_chunks if r.get('document_name')}))) or 'Internal Technical Documentation'}."
            )

            return (
                "I will now compile the retrieved technical findings and citations into an official PDF document.",
                "generate_pdf_report",
                {
                    "title": title,
                    "executive_summary": summary,
                    "sections": sections,
                    "findings": findings[:6],
                    "sop_citations": citations,
                },
            )

        if has_generated_pdf:
            return (
                "Official PDF report has been compiled and verified. Ready to present final summary to user.",
                "final_answer",
                {},
            )

        # Call Reasoning Model for Step Planning
        try:
            res = self.model_client.generate_text(
                model_name=settings.models.reasoning,
                prompt=step_prompt,
                max_tokens=400,
                project_id=project_id,
            )
            raw_text = res.get("response", "")
            parsed = self.model_client.extract_json_from_response(raw_text)
            if parsed and "action" in parsed:
                action = parsed.get("action", "")
                thought = parsed.get("thought", "Proceeding with next tool action.")
                inp = parsed.get("action_input", {})
                if action in self._tools or action == "final_answer":
                    return thought, action, inp
        except Exception as e:
            logger.debug(f"Planner LLM generation note: {e}")

        # Fallback: conclude if step > 1
        return "Sufficient technical context gathered. Ready to synthesize verified answer.", "final_answer", {}

