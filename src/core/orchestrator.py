    def get_registered_tools(self) -> List[ToolDefinition]:
        """Returns schemas of all registered tools."""
        return [item["definition"] for item in self._tools.values()]

    def execute_tool(self, tool_name: str, params: Dict[str, Any], project_id: str) -> Dict[str, Any]:
        """Executes a tool by name with safety checks."""
        if tool_name not in self._tools:
            return {"status": "error", "error": f"Unknown tool '{tool_name}'. Available: {list(self._tools.keys())}"}
        handler = self._tools[tool_name]["handler"]
        try:
            return handler(params, project_id)
        except Exception as e:
            logger.error(f"Error executing tool {tool_name}: {e}", exc_info=True)
            return {"status": "error", "error": str(e)}

